import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('shows a retry when the records service is unavailable', async ({ page }) => {
  await page.route('**/api/**', (route) => route.abort())
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('Check that the app server is running')
  await expect(page.getByText('Opening local records')).toHaveCount(0)

  await page.unroute('**/api/**')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByRole('heading', { name: 'Good day' })).toBeVisible()
  const rewrittenApiResponse = await page.request.get('/api/index?path=data')
  expect(rewrittenApiResponse.ok()).toBeTruthy()
  await expect(rewrittenApiResponse.json()).resolves.toHaveProperty('settings')
})

test('issues an invoice, records installments, and downloads a linked receipt PDF', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Good day' })).toBeVisible()
  await page.getByRole('button', { name: 'Create invoice' }).first().click()

  await page.getByLabel('Guest name').fill('Browser Test Guest')
  await page.getByLabel('Phone number').fill('+254700123456')
  await page.getByLabel('Unit name').fill('One bedroom unit')
  await page.getByLabel('Default rate per night').fill('9000')
  await page.getByLabel('Rate', { exact: true }).fill('9000')
  await page.getByLabel('Line total').fill('9000')
  await page.getByRole('button', { name: 'Create draft invoice' }).click()
  await expect(page.getByText('Invoice draft created. Issue it when it is ready to send.')).toBeVisible()

  await page.getByRole('button', { name: 'Invoices' }).click()
  await page.getByRole('button', { name: 'Issue', exact: true }).click()
  await expect(page.getByText('Invoice issued. No payment was recorded.')).toBeVisible()
  await page.getByRole('button', { name: 'Pay', exact: true }).click()
  await page.getByLabel(/Paste M-Pesa confirmation message/).fill('Confirmed. You have received KES 3000.00 for Account 242025 from BROWSER TEST GUEST. # Mpesa Ref:UJHLP9YDVS on 17-10-2026 09:59Hrs')
  await expect(page.getByLabel('Amount received')).toHaveValue('3000')
  await expect(page.getByLabel('M-Pesa transaction reference')).toHaveValue('UJHLP9YDVS')
  await expect(page.getByLabel('Payment date and time (Kenya time)')).toHaveValue('2026-10-17T09:59')
  await expect(page.locator('.parsed-message')).toContainText('Account 242025')
  await page.getByLabel(/I confirm this payment was actually received/).check()
  await page.getByRole('button', { name: 'Record payment & issue receipt' }).click()
  await expect(page.getByText('Payment recorded and receipt issued.')).toBeVisible()
  await expect(page.getByText('KSh 6,000.00')).toBeVisible()

  await page.getByRole('button', { name: 'Pay', exact: true }).click()
  await page.getByLabel('Amount received').fill('6000')
  await page.getByLabel('M-Pesa transaction reference').fill('BROWSER-MPESA-2')
  await page.getByLabel(/I confirm this payment was actually received/).check()
  await page.getByRole('button', { name: 'Record payment & issue receipt' }).click()
  await expect(page.getByText('Payment recorded and receipt issued.')).toBeVisible()
  await expect(page.getByText('KSh 0.00')).toBeVisible()

  await page.getByRole('button', { name: 'Receipts', exact: true }).click()
  await expect(page.getByText('2 receipts')).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.locator('button[title="Download PDF"]').first().click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toContain('Receipt-SHS-00002')
  const path = await download.path()
  expect(path).toBeTruthy()
  const pdf = await readFile(path!)
  expect(pdf.subarray(0, 5).toString()).toBe('%PDF-')
  expect(pdf.toString('latin1')).toContain('PAYMENT RECEIPT')
  expect(pdf.toString('latin1')).toContain('BROWSER-MPESA-2')
  const shareDownload = page.waitForEvent('download')
  const whatsappPopup = page.waitForEvent('popup')
  await page.getByRole('button', { name: 'Share receipt' }).first().click()
  const [sharedPdf, whatsapp] = await Promise.all([shareDownload, whatsappPopup])
  expect(sharedPdf.suggestedFilename()).toContain('Receipt-SHS-00002')
  expect(whatsapp.url()).toMatch(/(wa\.me|whatsapp\.com).*text=/)
  expect(decodeURIComponent(whatsapp.url())).toContain('SHS/00002')
})

test('keeps the dashboard within a mobile viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Good day' })).toBeVisible()
  const dimensions = await page.evaluate(() => ({ client: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }))
  expect(dimensions.scroll).toBeLessThanOrEqual(dimensions.client)
  await page.screenshot({ path: '/tmp/shwari-dashboard-mobile.png', fullPage: true })
})

